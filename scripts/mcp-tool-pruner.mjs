#!/usr/bin/env node
/**
 * AirMentor MCP Tool Pruner
 * SOTA 2026: Eliminate unused MCP tools from context to prevent token bloat
 * Inspired by: GitHub (62% token savings), Atlassian MCP-compressor (70-97% reduction)
 *
 * Problem: MCP servers register ALL tools in every request. 40 tools = 10-15KB overhead per turn.
 * Solution: Track actual tool usage, prune unused tools from agent config.
 *
 * Usage: node scripts/mcp-tool-pruner.mjs --audit  (shows unused tools)
 *        node scripts/mcp-tool-pruner.mjs --prune  (removes from active config)
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const auditDir = path.join(repoRoot, '.audit')

// Read tool usage log (generated by agent runs)
const USAGE_LOG = path.join(auditDir, 'mcp-tool-usage.jsonl')
const MCP_CONFIG = path.join(repoRoot, '.mcp-servers.json') // Your MCP server config

function loadUsageLog() {
  if (!existsSync(USAGE_LOG)) return []
  return readFileSync(USAGE_LOG, 'utf8')
    .split('\n')
    .filter(Boolean)
    .map(line => {
      try { return JSON.parse(line) } catch { return null }
    })
    .filter(Boolean)
}

function analyzeToolUsage(logs, days = 7) {
  const cutoff = new Date(Date.now() - days * 24 * 60 * 60 * 1000)
  const recentLogs = logs.filter(l => new Date(l.timestamp) >= cutoff)

  const usage = {} // toolName -> callCount
  const serverUsage = {} // serverName -> { toolCount, callCount }

  for (const log of recentLogs) {
    const tool = log.tool || log.toolName
    const server = log.server || 'unknown'
    if (!tool) continue

    usage[tool] = (usage[tool] || 0) + 1
    if (!serverUsage[server]) serverUsage[server] = { toolCount: 0, callCount: 0 }
    serverUsage[server].callCount++
  }

  // Count unique tools per server
  for (const log of recentLogs) {
    const server = log.server || 'unknown'
    if (!serverUsage[server]) serverUsage[server] = { toolCount: 0, callCount: 0 }
  }

  return { usage, serverUsage, totalCalls: recentLogs.length, daysAnalyzed: days }
}

function pruneUnusedTools(config, usage, threshold = 0) {
  const pruned = { ...config }
  const savings = { tokensBefore: 0, tokensAfter: 0, toolsRemoved: 0 }

  for (const server of Object.keys(pruned.servers || {})) {
    const serverConfig = pruned.servers[server]
    const originalTools = serverConfig.tools || []
    const usedTools = originalTools.filter(t => (usage[t.name] || 0) > threshold)
    const removed = originalTools.filter(t => (usage[t.name] || 0) <= threshold)

    savings.toolsRemoved += removed.length
    savings.tokensBefore += estimateToolTokens(originalTools)
    savings.tokensAfter += estimateToolTokens(usedTools)

    if (usedTools.length === 0 && originalTools.length > 0) {
      // Server has tools but none used — keep 3 most common as fallback
      const top3 = originalTools.slice(0, 3)
      serverConfig.tools = top3
    } else {
      serverConfig.tools = usedTools
    }
  }

  return { config: pruned, savings }
}

function estimateToolTokens(tools) {
  // Rough estimate: each tool schema ~200-500 tokens
  return tools.length * 350
}

// Main
const action = process.argv[2]
if (action === '--audit') {
  const logs = loadUsageLog()
  const analysis = analyzeToolUsage(logs, 7)

  console.log('=== MCP Tool Usage Audit ===')
  console.log(`Days analyzed: ${analysis.daysAnalyzed}`)
  console.log(`Total tool calls: ${analysis.totalCalls}`)
  console.log('')

  const sortedTools = Object.entries(analysis.usage).sort((a, b) => b[1] - a[1])
  console.log('Tool usage ranking:')
  for (const [tool, count] of sortedTools) {
    const status = count === 0 ? 'UNUSED' : count < 3 ? 'RARE' : 'ACTIVE'
    console.log(`  ${tool}: ${count} calls (${status})`)
  }

  const unused = sortedTools.filter(([, count]) => count === 0)
  const rare = sortedTools.filter(([, count]) => count > 0 && count < 3)

  console.log('')
  console.log(`Unused tools (can prune): ${unused.length}`)
  console.log(`Rarely used tools (consider pruning): ${rare.length}`)
  console.log(`Estimated token savings if pruned: ${(unused.length + rare.length) * 350} tokens/request`)
} else if (action === '--prune') {
  if (!existsSync(MCP_CONFIG)) {
    console.log(`MCP config not found at ${MCP_CONFIG}`)
    console.log('Create it with your server definitions, then run again.')
    process.exit(1)
  }

  const config = JSON.parse(readFileSync(MCP_CONFIG, 'utf8'))
  const logs = loadUsageLog()
  const { usage } = analyzeToolUsage(logs, 7)
  const { config: pruned, savings } = pruneUnusedTools(config, usage)

  const backupFile = `${MCP_CONFIG}.backup.${Date.now()}`
  writeFileSync(backupFile, JSON.stringify(config, null, 2))
  writeFileSync(MCP_CONFIG, JSON.stringify(pruned, null, 2))

  console.log('=== MCP Tool Prune Complete ===')
  console.log(`Backup saved to: ${backupFile}`)
  console.log(`Tools removed: ${savings.toolsRemoved}`)
  console.log(`Token reduction: ${savings.tokensBefore} → ${savings.tokensAfter} (${Math.round((1 - savings.tokensAfter/savings.tokensBefore)*100)}%)`)
} else {
  console.log(`Usage:
  node scripts/mcp-tool-pruner.mjs --audit  (show usage analysis)
  node scripts/mcp-tool-pruner.mjs --prune  (remove unused tools)`)
}
